//! The tool: one compiled export, run from a shell.
//!
//! Every other entry in purzig is a *program*: `rt.runEffect(main())` and the
//! process lives and dies with the PureScript `main`. A tool is a *subcommand
//! runner* instead -- the process is a thin CLI whose arguments say which
//! export to call and where the bytes come from. That is what lets a build
//! graph, a shell script or another program use a PureScript function without
//! a PureScript program around it, which is issue #45's whole point.
//!
//! The contract, in full:
//!
//! ```text
//! <tool> run <export> [<infile>]   bytes in, bytes out (see below)
//! <tool> list                      the .exports names, one per line
//! <tool> --version                 "<name> <version>"
//! ```
//!
//! `run` reads its input bytes from `infile`, or from stdin when `infile` is
//! omitted. **No bytes at all** means "call the export with zero arguments":
//! the export's value is the result, which is how a nullary PureScript binding
//! produces a seed file. **Any bytes at all** means "codec-decode exactly one
//! `rt.Value` and apply the export to it". The result is codec-encoded to
//! stdout, so the whole pipe is `valuecodec` on both ends and a tool composes
//! with itself: the output of one `run` is a valid `infile` for the next.
//!
//! Exit codes: 0 success; 1 the call or the codec refused (stderr names the
//! `Error`); 2 the command line was wrong or named an export that `.exports`
//! does not contain. Nothing but the encoded value ever reaches stdout -- every
//! diagnostic goes to stderr -- so `tool run f > out.bin` is always safe.
//!
//! Arity is v1's one unresolved question, and it is deliberately not answered
//! here: there is no syntax for "k arguments". `.exports` names an export, not
//! a shape, and the manifest that knows the shapes lives in the build cache
//! where a build script cannot read it at configure time. See
//! `docs/handoff-tool-codec-part2-2026-11-08.md`.
//!
//! Like `entry/entry.zig` this file is shipped, not generated: `addTool`
//! compiles it as-is. What it cannot know on its own -- the names it answers
//! to, and which generated modules to look them up in -- arrives as the
//! `tool_registry` module that `addTool` writes into the build cache.

const std = @import("std");
const rt = @import("runtime");

/// GENERATED by `purzig.addTool`: `tool_name`, `version`, `exports`, and
/// `modules` (each a `.name` and the generated `.mod` to look it up in).
const registry = @import("tool_registry");

/// Every top-level PureScript decl is emitted as exactly this: a nullary
/// function returning the value. Not a constant, because `rt.apply` allocates
/// (see `Zig.Emit.emitTopValue`).
const Thunk = *const fn () rt.Error!rt.Value;

const exit_ok: u8 = 0;
/// The call raised, or the codec refused to turn bytes into a `Value` (or a
/// `Value` into bytes).
const exit_refused: u8 = 1;
/// The command line, or an export name that `.exports` does not list.
const exit_usage: u8 = 2;

pub fn main(init: rt.ProcessInit) !void {
    // One arena for the whole process: the runtime borrows it (`rt.init`), and
    // so does everything this CLI allocates. A tool run is short-lived, so the
    // arena's "never free" is exactly the right lifetime -- and the decoded
    // argument has to outlive the call, which a per-statement allocator would
    // not give us.
    const arena = init.arena.allocator();
    rt.init(init.io, arena);

    const code = dispatch(init.io, arena, init.minimal.args);
    if (code != exit_ok) std.process.exit(code);
}

// --- commands --------------------------------------------------------------

fn dispatch(io: std.Io, arena: std.mem.Allocator, args: std.process.Args) u8 {
    var argv: std.ArrayList([]const u8) = .empty;
    var it = args.iterate();
    while (it.next()) |arg| argv.append(arena, arg) catch return usage(io, arena);

    // argv[0] is the tool's own path: `run` is at argv[1].
    const rest = if (argv.items.len > 0) argv.items[1..] else argv.items;
    if (rest.len == 0) return usage(io, arena);

    const command = rest[0];
    if (std.mem.eql(u8, command, "--version")) return printVersion(io, arena);
    if (std.mem.eql(u8, command, "list")) return printList(io, arena);
    if (std.mem.eql(u8, command, "run")) return runExport(io, arena, rest[1..]);
    return usage(io, arena);
}

fn printVersion(io: std.Io, arena: std.mem.Allocator) u8 {
    const line = std.fmt.allocPrint(arena, "{s} {s}\n", .{
        registry.tool_name,
        registry.version,
    }) catch return exit_refused;
    return emit(io, line);
}

fn printList(io: std.Io, arena: std.mem.Allocator) u8 {
    var out: std.ArrayList(u8) = .empty;
    for (registry.exports) |name| {
        out.appendSlice(arena, name) catch return exit_refused;
        out.append(arena, '\n') catch return exit_refused;
    }
    return emit(io, out.items);
}

fn runExport(io: std.Io, arena: std.mem.Allocator, rest: []const []const u8) u8 {
    if (rest.len == 0 or rest.len > 2) return usage(io, arena);
    const name = rest[0];

    if (!isListed(name)) return reportUnknownExport(io, arena, name);
    const thunk = lookup(name) orelse return reportNotEmitted(io, arena, name);

    const input = if (rest.len == 2)
        readPath(io, arena, rest[1]) catch |err|
            return refuse(io, arena, "run {s}: {s}: {s}\n", .{ name, rest[1], @errorName(err) })
    else
        readStdin(io, arena) catch |err|
            return refuse(io, arena, "run {s}: stdin: {s}\n", .{ name, @errorName(err) });

    // The thunk itself can raise (a top-level binding may be `unsafePerformEffect`
    // or a throwing `throw`), so it is a `rt.Error!rt.Value` like any call.
    const value = thunk() catch |err| return reportRaised(io, arena, name, err);

    const result = if (input.len == 0)
        value
    else blk: {
        // `rt.apply` traps when the callee is not a closure, so the check has to
        // come first: bytes in with a non-function export is a usage error, not
        // a panic in the runtime.
        if (value != .closure) {
            return misuse(io, arena, "run {s}: export takes no arguments, but {d} input bytes were given\n", .{ name, input.len });
        }
        var reader = rt.valuecodec.Reader.init(input);
        const argument = rt.valuecodec.decode(&reader, arena) catch |err|
            return refuse(io, arena, "run {s}: input: {s}\n", .{ name, @errorName(err) });
        break :blk rt.apply(value, argument) catch |err| return reportRaised(io, arena, name, err);
    };

    // A closure here means the export wanted the argument it did not get. The
    // codec would say `Unencodable`, which is true but unhelpful.
    if (result == .closure) {
        return misuse(io, arena, "run {s}: export is a function; its arguments were not supplied\n", .{name});
    }

    const bytes = rt.valuecodec.encodeTo(arena, result) catch |err|
        return refuse(io, arena, "run {s}: result: {s}\n", .{ name, @errorName(err) });
    return emit(io, bytes);
}

// --- export lookup ---------------------------------------------------------

/// Is `name` one of the names this tool was configured with? Asked separately
/// from `lookup` so the two failures stay distinguishable: "not in `.exports`"
/// is a rejection, while "listed but not emitted" is a purzig bug worth its own
/// message.
fn isListed(name: []const u8) bool {
    for (registry.exports) |listed| {
        if (std.mem.eql(u8, listed, name)) return true;
    }
    return false;
}

/// Resolve a runtime name to a thunk. `registry.exports` is comptime-known, so
/// the loop unrolls into one `if` per export and `thunkFor` -- which needs a
/// comptime name to spell `@"ps.<name>"` -- is instantiated once per export.
fn lookup(name: []const u8) ?Thunk {
    inline for (registry.exports) |listed| {
        if (std.mem.eql(u8, listed, name)) return thunkFor(listed);
    }
    return null;
}

/// The export's decl, in whichever generated module has it. `@hasDecl` rather
/// than a compile error: `.exports` is the consumer's list and the codegen is
/// the truth, so a mismatch must be a runtime diagnostic, not a build failure.
fn thunkFor(comptime name: []const u8) ?Thunk {
    inline for (registry.modules) |m| {
        if (@hasDecl(m.mod, "ps." ++ name)) return &@field(m.mod, "ps." ++ name);
    }
    return null;
}

// --- bytes in, bytes out ---------------------------------------------------

fn readPath(io: std.Io, arena: std.mem.Allocator, path: []const u8) ![]const u8 {
    const file = try std.Io.Dir.cwd().openFile(io, path, .{});
    defer file.close(io);
    return readToEnd(io, arena, file);
}

fn readStdin(io: std.Io, arena: std.mem.Allocator) ![]const u8 {
    const stdin = std.Io.File.stdin();
    // A terminal never reaches end of input, so `run <export>` typed at a
    // prompt would wait forever. "No bytes" is the zero-argument case, which is
    // exactly what someone typing the command by hand means.
    if (stdin.isTty(io) catch false) return &.{};
    return readToEnd(io, arena, stdin);
}

/// Read until end of input. Streaming rather than a sized read because the
/// tool is also how a large value gets in, and the arena means the pieces need
/// no reallocation dance.
///
/// `File.readStreaming` reports the end of the stream as `error.EndOfStream`,
/// NOT as a zero return: it is the streaming half of the `Io` interface, where
/// "no bytes this time" and "no more bytes ever" have to be told apart. Every
/// ordinary file therefore ends in that error, and it is the loop's exit, not a
/// failure. Measured, not guessed: reading a fixture to exhaustion and treating
/// only `n == 0` as the end turned a 2-byte infile into `EndOfStream` on stderr.
fn readToEnd(io: std.Io, arena: std.mem.Allocator, file: std.Io.File) ![]const u8 {
    var bytes: std.ArrayList(u8) = .empty;
    var buffer: [16 * 1024]u8 = undefined;
    while (true) {
        const n = file.readStreaming(io, &.{&buffer}) catch |err| switch (err) {
            error.EndOfStream => return bytes.items,
            else => return err,
        };
        if (n == 0) return bytes.items;
        try bytes.appendSlice(arena, buffer[0..n]);
    }
}

fn emit(io: std.Io, bytes: []const u8) u8 {
    std.Io.File.stdout().writeStreamingAll(io, bytes) catch return exit_refused;
    return exit_ok;
}

// --- diagnostics -----------------------------------------------------------

/// Every diagnostic is `<tool>: ...` on stderr, and every diagnostic has an
/// exit code: 1 when the call or the codec refused, 2 when the caller asked for
/// something that is not there.
fn say(io: std.Io, arena: std.mem.Allocator, comptime fmt: []const u8, args: anytype) void {
    const message = std.fmt.allocPrint(arena, "{s}: " ++ fmt, .{registry.tool_name} ++ args) catch return;
    std.Io.File.stderr().writeStreamingAll(io, message) catch {};
}

fn refuse(io: std.Io, arena: std.mem.Allocator, comptime fmt: []const u8, args: anytype) u8 {
    say(io, arena, fmt, args);
    return exit_refused;
}

fn misuse(io: std.Io, arena: std.mem.Allocator, comptime fmt: []const u8, args: anytype) u8 {
    say(io, arena, fmt, args);
    return exit_usage;
}

/// A raised PureScript value. `rt.Error` is a bare tag, so the payload lives in
/// the runtime's side channel -- and it is only meaningful if it is taken.
fn reportRaised(io: std.Io, arena: std.mem.Allocator, name: []const u8, err: rt.Error) u8 {
    const thrown = switch (err) {
        error.PsException => rt.takeError(),
    };
    return switch (thrown) {
        .string => |s| refuse(io, arena, "run {s}: exception: {s}\n", .{ name, s }),
        else => refuse(io, arena, "run {s}: exception (a {s} value, not a string)\n", .{ name, @tagName(thrown) }),
    };
}

fn reportUnknownExport(io: std.Io, arena: std.mem.Allocator, name: []const u8) u8 {
    var allowed: std.ArrayList(u8) = .empty;
    for (registry.exports, 0..) |listed, i| {
        if (i != 0) allowed.appendSlice(arena, ", ") catch return exit_refused;
        allowed.appendSlice(arena, listed) catch return exit_refused;
    }
    if (allowed.items.len == 0) allowed.appendSlice(arena, "(none)") catch return exit_refused;
    return misuse(io, arena, "unknown export \"{s}\"; allowed: {s}\n", .{ name, allowed.items });
}

fn reportNotEmitted(io: std.Io, arena: std.mem.Allocator, name: []const u8) u8 {
    return misuse(io, arena, "export \"{s}\" is listed in .exports but no generated module emits it\n", .{name});
}

fn usage(io: std.Io, arena: std.mem.Allocator) u8 {
    // The tool's own name, in the tool's own words: `usage: example-tool run ...`
    // reads better than a `<tool>` placeholder nobody can paste.
    const message = std.fmt.allocPrint(arena,
        \\usage: {s} run <export> [<infile>]
        \\       {s} list
        \\       {s} --version
        \\
    , .{ registry.tool_name, registry.tool_name, registry.tool_name }) catch return exit_usage;
    std.Io.File.stderr().writeStreamingAll(io, message) catch {};
    return exit_usage;
}
